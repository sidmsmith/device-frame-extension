LANGS = {'en': EN, 'fr': FR, 'es_419': ES_MX}

if __name__ == '__main__':
    for lang, table in LANGS.items():
        missing = set(EN) - set(table)
        extra = set(table) - set(EN)
        assert not missing and not extra, (lang, sorted(missing), sorted(extra))
        out = ROOT / '_locales' / lang / 'messages.json'
        out.parent.mkdir(parents=True, exist_ok=True)
        data = {k: {'message': v} for k, v in table.items()}
        out.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
        print(f'{out.relative_to(ROOT)}: {len(table)} messages')
